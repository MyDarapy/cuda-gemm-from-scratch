#!/usr/bin/env python3
"""
bench_matmul.py - progressive benchmark of our FP32 GEMM kernels against cuBLAS.

Every kernel lives in a .cu file under cuda/ and exposes the same host function,
declared in cuda/gemm_kernels.cuh:

    void sgemm_<name>(const Tensor& A, const Tensor& B, Tensor& C, float alpha, float beta)
    // C = alpha * (A @ B) + beta * C,  A: MxK, B: KxN, C: MxN, fp32 row-major

Each kernel is built as its own extension, so a kernel that is not written yet
(or does not compile) never blocks the others. Results are saved per kernel, so
you benchmark one kernel at a time and the plots grow as you go.

Adding a kernel:
  1. write cuda/foo.cu with its kernel and host function sgemm_foo(...)
  2. declare sgemm_foo in cuda/gemm_kernels.cuh
  3. add a line to KERNELS below (source paths are relative to the repo root)

Layout: cuda/ holds the kernels and gemm_kernels.cuh, scripts/ holds these
scripts and utils.cuh; build/, results/ and plots/ go in the repo root.

Usage (run from anywhere: paths are resolved from this file):
  python bench_matmul.py --list                  # registered kernels and saved results
  python bench_matmul.py -k naive                # build, check, benchmark -> results/naive.csv
  python bench_matmul.py -k naive --quick        # few sizes, short budget, while iterating
  python bench_matmul.py -k naive --tag bs16     # a variant -> results/naive-bs16.csv
  python bench_matmul.py -k naive -k coalesced   # several kernels in one run
  python bench_matmul.py -k all
  python plot_bench.py                           # plots every kernel saved in results/

Each run:
  * correctness: odd, non-multiple-of-32 shapes and alpha/beta != (1, 0),
    compared against an fp64 reference, then every benchmark size
  * timing: CUDA events around one launch, L2 flush (4x the L2 size) outside the events,
    median of N runs; cuBLAS (TF32 off) timed in the same run on the same inputs
  * results/<label>.csv (latest) and results/history/<label>_<timestamp>.csv
"""
import argparse
import csv
import datetime as dt
import math
import os
import statistics
import sys
import traceback
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parent.parent  # repo root
SCRIPTS_DIR = ROOT / "scripts"
KERNEL_DIR = ROOT / "cuda"
RESULTS_DIR = ROOT / "results"
BUILD_DIR = ROOT / "build"

# name -> source file and host function. Order here is the order of the progression.
KERNELS = {
    "naive": {"source": "cuda/naive.cu", "func": "sgemm_naive"},
    "coalesced": {"source": "cuda/memory_coalescing.cu", "func": "sgemm_coalesced"},
    "shared_mem": {"source": "cuda/memory_coalescing.cu", "func": "sgemm_shared_mem"},
    # "tiling_1d": {"source": "cuda/1D-tiling.cu", "func": "sgemm_tiling_1d"},
    # "tiling_2d": {"source": "cuda/2D-tiling.cu", "func": "sgemm_tiling_2d"},
    # "warptiling": {"source": "cuda/warptiling.cu", "func": "sgemm_warptiling"},
}

# Reference numbers per GPU (boost clock, dense), matched against the device name.
# First substring match wins, so longer names go first (L40S before L4, A100 before A10).
# Unknown GPUs still run; their % peak column and peak lines are left empty.
GPU_SPECS = {
    "4090": {"peak_tflops": 82.6, "peak_gbs": 1008.0, "l2_bytes": 72 * 1024 * 1024},
    "L40S": {"peak_tflops": 91.6, "peak_gbs": 864.0, "l2_bytes": 96 * 1024 * 1024},
    "L4": {"peak_tflops": 30.3, "peak_gbs": 300.0, "l2_bytes": 48 * 1024 * 1024},
    "A100": {"peak_tflops": 19.5, "peak_gbs": 1555.0, "l2_bytes": 40 * 1024 * 1024},
    "A10": {"peak_tflops": 31.2, "peak_gbs": 600.0, "l2_bytes": 6 * 1024 * 1024},
    "H100": {"peak_tflops": 66.9, "peak_gbs": 3350.0, "l2_bytes": 50 * 1024 * 1024},
}


def gpu_spec(name):
    for key, spec in GPU_SPECS.items():
        if key in name:
            return spec
    return {"peak_tflops": float("nan"), "peak_gbs": float("nan"), "l2_bytes": None}


DEFAULT_SIZES = [256, 512, 1024, 2048, 3072, 4096, 6144, 8192]
QUICK_SIZES = [512, 1024, 2048, 4096]

# (M, N, K) shapes for the correctness pass: odd sizes and non-square shapes catch
# boundary-check and indexing bugs that square multiples of 32 hide.
CHECK_SHAPES = [
    (128, 128, 128),
    (127, 129, 65),
    (1, 257, 33),
    (300, 1, 77),
    (513, 257, 1029),
    (1024, 768, 512),
]
CHECK_ALPHA_BETA = [(1.0, 0.0), (1.5, -0.5)]

BINDING_TEMPLATE = """\
// generated by bench_matmul.py - do not edit
#include <torch/extension.h>
#include "gemm_kernels.cuh"

PYBIND11_MODULE(TORCH_EXTENSION_NAME, m) {{
    m.def("gemm", &{func}, "C = alpha * (A @ B) + beta * C");
}}
"""


def parse_args():
    p = argparse.ArgumentParser(description="Benchmark our GEMM kernels against cuBLAS, one kernel at a time")
    p.add_argument("-k", "--kernel", action="append", default=[],
                   help="Kernel name from KERNELS (repeatable), or 'all'")
    p.add_argument("--list", action="store_true", help="List registered kernels and saved results, then exit")
    p.add_argument("--tag", default=None,
                   help="Save as <kernel>-<tag> so variants of one kernel can be compared")
    p.add_argument("--sizes", nargs="+", type=int, default=None,
                   help=f"Square sizes M = N = K (default {DEFAULT_SIZES})")
    p.add_argument("--quick", action="store_true",
                   help=f"Sizes {QUICK_SIZES} and a 0.3 s budget per kernel per size")
    p.add_argument("--time-budget", type=float, default=1.0,
                   help="Approx. seconds of timed runs per kernel per size")
    p.add_argument("--min-iters", type=int, default=5)
    p.add_argument("--max-iters", type=int, default=200)
    p.add_argument("--warmup", type=int, default=3, help="Max warmup runs (fewer for slow kernels)")
    p.add_argument("--no-flush-l2", action="store_true", help="Keep L2 warm between runs")
    p.add_argument("--rtol", type=float, default=1e-4,
                   help="Max error relative to max|reference| for the correctness check")
    p.add_argument("--skip-check", action="store_true", help="Skip the correctness pass")
    p.add_argument("--force", action="store_true", help="Benchmark even if the correctness check fails")
    p.add_argument("--no-save", action="store_true", help="Print results only, don't write CSVs")
    p.add_argument("--verbose-build", action="store_true", help="Show the full nvcc/ninja output")
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()
    if args.quick:
        args.sizes = args.sizes or QUICK_SIZES
        args.time_budget = min(args.time_budget, 0.3)
    args.sizes = args.sizes or DEFAULT_SIZES
    return args


# ---------------------------------------------------------------- build

def build(name, spec, verbose):
    """JIT-compiles one kernel's .cu plus a generated binding into its own module."""
    from torch.utils.cpp_extension import load

    source = ROOT / spec["source"]
    if not source.exists():
        raise FileNotFoundError(f"{source} does not exist")

    build_dir = BUILD_DIR / name
    build_dir.mkdir(parents=True, exist_ok=True)
    binding = build_dir / "binding.cpp"
    text = BINDING_TEMPLATE.format(func=spec["func"])
    if not binding.exists() or binding.read_text() != text:  # rewriting would force a rebuild
        binding.write_text(text)

    mod = load(
        name=f"gemm_{name}",
        sources=[str(source), str(binding)],
        extra_include_paths=[str(KERNEL_DIR), str(SCRIPTS_DIR)],
        extra_cflags=["-O3"],
        extra_cuda_cflags=["-O3", "-lineinfo"],
        build_directory=str(build_dir),
        verbose=verbose,
    )
    return mod.gemm


# ---------------------------------------------------------------- correctness

def max_rel_err(out, ref):
    """max |out - ref| / max |ref|, inf if out has NaN/Inf."""
    if not torch.isfinite(out).all():
        return math.inf
    scale = ref.abs().max().item()
    err = (out.double() - ref).abs().max().item()
    return err / scale if scale > 0 else err


def check_shapes(gemm, rtol):
    """Odd shapes and alpha/beta != (1, 0). Returns (ok, list of failure strings)."""
    failures = []
    for M, N, K in CHECK_SHAPES:
        A = torch.randn(M, K, device="cuda")
        B = torch.randn(K, N, device="cuda")
        C0 = torch.randn(M, N, device="cuda")
        AB = A.double() @ B.double()
        for alpha, beta in CHECK_ALPHA_BETA:
            C = C0.clone()
            try:
                gemm(A, B, C, alpha, beta)
                torch.cuda.synchronize()
            except Exception as ex:
                failures.append(f"{M}x{N}x{K} alpha={alpha} beta={beta}: {ex}")
                continue
            rel = max_rel_err(C, alpha * AB + beta * C0.double())
            if not rel <= rtol:
                failures.append(f"{M}x{N}x{K} alpha={alpha} beta={beta}: rel err {rel:.2e}")
    return not failures, failures


# ---------------------------------------------------------------- timing

class L2Flusher:
    """Writes a buffer 4x the L2 size so each timed run starts with a cold cache."""
    def __init__(self, enabled, l2_bytes):
        self.buf = torch.empty(4 * l2_bytes // 4, dtype=torch.int32, device="cuda") if enabled else None

    def __call__(self):
        if self.buf is not None:
            self.buf.zero_()


def time_runs(run, args, flush):
    """Per-launch times in ms. run() launches exactly one GEMM on the current stream."""
    # Untimed run first: the first call of a shape can pay one-time costs (cuBLAS
    # handle/workspace setup, heuristic lookup) that would inflate the probe below.
    run()
    torch.cuda.synchronize()

    # Probe once to size warmup and iteration count, so an 8 s naive launch
    # and a 50 us cuBLAS launch both get a sensible number of runs.
    s, e = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
    flush()
    s.record()
    run()
    e.record()
    torch.cuda.synchronize()
    est_s = max(s.elapsed_time(e) / 1e3, 1e-6)

    for _ in range(max(1, min(args.warmup, int(0.2 / est_s)))):
        run()
    torch.cuda.synchronize()

    iters = int(min(args.max_iters, max(args.min_iters, args.time_budget / est_s)))
    starts = [torch.cuda.Event(enable_timing=True) for _ in range(iters)]
    ends = [torch.cuda.Event(enable_timing=True) for _ in range(iters)]
    for i in range(iters):
        flush()  # outside the events: not timed
        starts[i].record()
        run()
        ends[i].record()
    torch.cuda.synchronize()
    return [st.elapsed_time(en) for st, en in zip(starts, ends)]


def summarize(times_ms, flops, bytes_min):
    med = statistics.median(times_ms)
    return {
        "median_ms": med,
        "min_ms": min(times_ms),
        "std_ms": statistics.stdev(times_ms) if len(times_ms) > 1 else 0.0,
        "iters": len(times_ms),
        "tflops": flops / (med / 1e3) / 1e12,
        "gbs": bytes_min / (med / 1e3) / 1e9,
    }


# ---------------------------------------------------------------- one kernel

def bench_kernel(name, label, gemm, args, flush, env):
    print(f"\n=== {label} ({KERNELS[name]['source']} :: {KERNELS[name]['func']}) ===")

    if not args.skip_check:
        ok, failures = check_shapes(gemm, args.rtol)
        if ok:
            print(f"[check] {len(CHECK_SHAPES) * len(CHECK_ALPHA_BETA)} odd-shape / alpha-beta cases OK")
        else:
            print(f"[check] FAILED {len(failures)} case(s):")
            for f in failures:
                print(f"        {f}")
            if not args.force:
                print("[check] not benchmarking an incorrect kernel (pass --force to time it anyway)")
                return None

    hdr = (f"{'size':>6} | {'ms':>10} {'cuBLAS ms':>10} | {'TFLOPS':>7} {'cuBLAS':>7} | "
           f"{'% cuBLAS':>8} {'% peak':>7} | {'GB/s':>7} | check")
    print(hdr)
    print("-" * len(hdr))

    rows = []
    for n in args.sizes:
        M = N = K = n
        A = torch.randn(M, K, device="cuda")
        B = torch.randn(K, N, device="cuda")
        C = torch.zeros(M, N, device="cuda")
        flops = 2.0 * M * N * K
        bytes_min = 4.0 * (M * K + K * N + M * N)

        row = {"kernel": label, "base_kernel": name, "size": n, "M": M, "N": N, "K": K,
               "flops": flops, "bytes": bytes_min, **env}

        if args.skip_check:
            check_str, row["rel_err"], row["correct"] = "skipped", "", ""
        else:
            try:
                gemm(A, B, C, 1.0, 0.0)
                torch.cuda.synchronize()
                rel = max_rel_err(C, A.double() @ B.double())
                ok = rel <= args.rtol
                check_str = f"{'OK' if ok else 'FAIL'} ({rel:.1e})"
                row["rel_err"], row["correct"] = rel, ok
            except Exception as ex:
                check_str, row["rel_err"], row["correct"] = f"ERROR: {ex}", "", False
            C.zero_()

        try:
            k = summarize(time_runs(lambda: gemm(A, B, C, 1.0, 0.0), args, flush), flops, bytes_min)
            c = summarize(time_runs(lambda: torch.mm(A, B, out=C), args, flush), flops, bytes_min)
        except Exception as ex:
            print(f"{n:>6} | [error] {ex}")
            continue

        row.update({f"{key}": v for key, v in k.items()})
        row.update({f"cublas_{key}": v for key, v in c.items()})
        row["pct_cublas"] = 100.0 * c["median_ms"] / k["median_ms"]
        row["pct_peak"] = 100.0 * k["tflops"] / env["peak_tflops"]
        rows.append(row)

        print(f"{n:>6} | {k['median_ms']:>10.3f} {c['median_ms']:>10.3f} | "
              f"{k['tflops']:>7.2f} {c['tflops']:>7.2f} | "
              f"{row['pct_cublas']:>7.1f}% {row['pct_peak']:>6.1f}% | {k['gbs']:>7.1f} | {check_str}",
              flush=True)

        del A, B, C
        torch.cuda.empty_cache()

    return rows


def save(label, rows, stamp):
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "history").mkdir(exist_ok=True)
    paths = [RESULTS_DIR / f"{label}.csv", RESULTS_DIR / "history" / f"{label}_{stamp}.csv"]
    for path in paths:
        with open(path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
    print(f"[save] {paths[0].relative_to(ROOT)} (+ history copy)")


def list_kernels():
    print("registered kernels (in progression order):")
    for name, spec in KERNELS.items():
        src = ROOT / spec["source"]
        saved = sorted(p.stem for p in RESULTS_DIR.glob(f"{name}*.csv")) if RESULTS_DIR.exists() else []
        status = "source ok" if src.exists() else "source MISSING"
        print(f"  {name:<14} {spec['source']:<28} {spec['func']:<22} {status:<15} "
              f"saved: {', '.join(saved) or '-'}")


# ---------------------------------------------------------------- main

def main():
    args = parse_args()
    if args.list:
        list_kernels()
        return
    if not args.kernel:
        sys.exit("[error] pick a kernel with -k (see --list)")

    names = list(KERNELS) if "all" in args.kernel else args.kernel
    unknown = [n for n in names if n not in KERNELS]
    if unknown:
        sys.exit(f"[error] unknown kernel(s) {unknown}; registered: {list(KERNELS)}")
    if args.tag and len(names) > 1:
        sys.exit("[error] --tag labels a single kernel's variant; pass one -k with it")
    if not torch.cuda.is_available():
        sys.exit("[error] CUDA not available")

    # True FP32 for cuBLAS, same as our kernels. With TF32 on, cuBLAS would run on
    # tensor cores at reduced precision and the % cuBLAS numbers would be meaningless.
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.manual_seed(args.seed)

    # Compile for the GPU we're on (8.9 for RTX 4090 / L40S)
    major, minor = torch.cuda.get_device_capability(0)
    os.environ.setdefault("TORCH_CUDA_ARCH_LIST", f"{major}.{minor}")

    gpu = torch.cuda.get_device_name(0)
    spec = gpu_spec(gpu)
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    env = {"gpu": gpu, "torch": torch.__version__, "cuda": torch.version.cuda,
           "timestamp": stamp, "flush_l2": not args.no_flush_l2,
           **{k: v for k, v in spec.items() if k != "l2_bytes"}}
    print(f"GPU: {gpu} | torch {torch.__version__} | CUDA {torch.version.cuda} | "
          f"tf32=off | flush_l2={not args.no_flush_l2} | sizes={args.sizes}")
    if math.isnan(spec["peak_tflops"]):
        print(f"[warn] no reference numbers for {gpu} in GPU_SPECS: % peak will be empty")

    props = torch.cuda.get_device_properties(0)
    l2_bytes = getattr(props, "L2_cache_size", 0) or spec["l2_bytes"] or 128 * 1024 * 1024
    flush = L2Flusher(enabled=not args.no_flush_l2, l2_bytes=l2_bytes)
    failed = []
    for name in names:
        label = f"{name}-{args.tag}" if args.tag else name
        try:
            print(f"\n[build] {name}: {KERNELS[name]['source']} ...", flush=True)
            gemm = build(name, KERNELS[name], args.verbose_build)
        except Exception as ex:
            print(f"[build] {name} FAILED: {ex}")
            if not args.verbose_build:
                print("        rerun with --verbose-build for the full compiler output")
            else:
                traceback.print_exc()
            failed.append(name)
            continue

        rows = bench_kernel(name, label, gemm, args, flush, env)
        if not rows:
            failed.append(name)
            continue
        if not args.no_save:
            save(label, rows, stamp)

    if failed:
        sys.exit(f"\n[done] failed: {failed}")
    print("\n[done] plot with: python plot_bench.py")


if __name__ == "__main__":
    main()
